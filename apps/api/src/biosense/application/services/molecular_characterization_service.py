"""Molecular Characterization module (Phase 1: mutation dimension only).

Input: biomarker (domain row) + cancer type + genomic data (live NCI GDC) +
literature (papers already linked to the biomarker in Postgres). Output: the
strict JSON shape from domain/entities/molecular_characterization.py.

`molecular_characteristics` is assembled only from structured fields we can
attribute to a real source (GDC gene/mutation records, linked papers) — never
freely generated by an LLM. Anything we cannot attribute is left out of the
list and named in `limitations` instead.
"""

from __future__ import annotations

from biosense.domain.entities.biomarker_dimension import (
    BiomarkerDimensionType,
    BiomarkerEvidenceStatus,
    EvidenceRef,
)
from biosense.domain.entities.methylation import CANCER_TYPE_TO_TCGA_PROJECTS
from biosense.domain.entities.molecular_characterization import (
    INSUFFICIENT_EVIDENCE,
    Detectability,
    MolecularCharacterizationResult,
)
from biosense.domain.services.normalization import normalize_gene_symbol
from biosense.infrastructure.external.gdc_client import GdcClient
from biosense.infrastructure.persistence.postgres.models import Biomarker


class MolecularCharacterizationService:
    def __init__(self, *, gdc: GdcClient | None = None) -> None:
        self._gdc = gdc or GdcClient()

    async def characterize(
        self,
        biomarker: Biomarker | None,
        *,
        cancer_code: str,
    ) -> MolecularCharacterizationResult:
        if biomarker is None:
            return MolecularCharacterizationResult(
                biomarker="",
                dimension=BiomarkerDimensionType.MUTATION.value,
                molecular_characteristics=[],
                detectability=Detectability(
                    is_detectable_in_ctdna=None,
                    mutation_count=None,
                    basis=INSUFFICIENT_EVIDENCE,
                    missing_data=True,
                ),
                specificity_features=[],
                limitations=[f"{INSUFFICIENT_EVIDENCE}: no biomarker candidate provided."],
                evidence=[],
                evidence_status=BiomarkerEvidenceStatus.INSUFFICIENT_EVIDENCE,
                evidence_status_reason="No biomarker candidate provided.",
            )

        ctdna_code = biomarker.ctdna.code if biomarker.ctdna else None
        if ctdna_code == "methylation":
            return await self._characterize_methylation(biomarker, cancer_code=cancer_code)
        if ctdna_code and ctdna_code != "mutation":
            return MolecularCharacterizationResult(
                biomarker=biomarker.name,
                dimension=ctdna_code,
                molecular_characteristics=[],
                detectability=None,
                specificity_features=[],
                limitations=[
                    f"Biomarker dimension '{ctdna_code}' is not yet supported by the "
                    "Molecular Characterization module — Phase 1 implements the "
                    "'mutation' dimension only."
                ],
                evidence=[],
                evidence_status=BiomarkerEvidenceStatus.PLANNED,
                evidence_status_reason=(
                    f"Dimension '{ctdna_code}' is planned but not yet implemented."
                ),
            )

        evidence: list[EvidenceRef] = [
            EvidenceRef(source=p.source, external_id=p.external_id, title=p.title)
            for p in (biomarker.papers or [])
        ]

        gene_symbol = biomarker.gene_symbol
        molecular_characteristics: list[str] = []
        specificity_features: list[str] = []
        limitations: list[str] = []
        detectability = Detectability(
            is_detectable_in_ctdna=None,
            mutation_count=None,
            basis=INSUFFICIENT_EVIDENCE,
            missing_data=True,
        )

        if gene_symbol:
            symbol = normalize_gene_symbol(gene_symbol)
            genes = await self._gdc.search_genes(symbol)
            mutation_count = await self._gdc.count_mutations_for_gene(symbol)
            gene = genes[0] if genes else None

            if gene is not None:
                molecular_characteristics.append(
                    f"Target gene {gene.name or symbol} ({symbol}), biotype "
                    f"{gene.biotype or INSUFFICIENT_EVIDENCE} (source: NCI GDC)."
                )
                specificity_features.append(
                    f"Gene-level specificity anchored to HGNC symbol {symbol} (source: NCI GDC)."
                )
                evidence.append(EvidenceRef(source="NCI GDC", external_id=gene.gene_id, title=gene.name or symbol))
            else:
                limitations.append(
                    f"{INSUFFICIENT_EVIDENCE}: NCI GDC has no gene record for symbol '{symbol}'."
                )

            if mutation_count is not None:
                molecular_characteristics.append(
                    f"{mutation_count} simple somatic mutation record(s) reported in NCI GDC "
                    f"for {symbol}."
                )
                detectability = Detectability(
                    is_detectable_in_ctdna=mutation_count > 0,
                    mutation_count=mutation_count,
                    basis=f"NCI GDC simple-somatic-mutation count for {symbol} = {mutation_count}.",
                    missing_data=False,
                )
            else:
                limitations.append(
                    f"{INSUFFICIENT_EVIDENCE}: NCI GDC mutation count unavailable for '{symbol}'."
                )
        else:
            limitations.append(
                f"{INSUFFICIENT_EVIDENCE}: biomarker '{biomarker.name}' has no gene_symbol "
                "recorded, so genomic characterization cannot be looked up."
            )

        if biomarker.description:
            molecular_characteristics.append(biomarker.description)

        if evidence:
            specificity_features.append(
                f"Backed by {len(evidence)} linked source(s) — see `evidence`."
            )
        else:
            limitations.append(f"{INSUFFICIENT_EVIDENCE}: no linked literature for this biomarker.")

        if not molecular_characteristics:
            limitations.append(
                f"{INSUFFICIENT_EVIDENCE}: no structured molecular characteristics could be "
                "derived for this biomarker — none are reported rather than guessed."
            )

        limitations.append(
            "Research use only — not a diagnostic system; findings require experimental "
            "(wet-lab) validation and carry no clinical or regulatory validity."
        )

        evidence_status, evidence_status_reason = self._evidence_status(
            molecular_characteristics=molecular_characteristics,
            evidence=evidence,
            detectability=detectability,
        )

        return MolecularCharacterizationResult(
            biomarker=biomarker.name,
            dimension=BiomarkerDimensionType.MUTATION.value,
            molecular_characteristics=molecular_characteristics,
            detectability=detectability,
            specificity_features=specificity_features,
            limitations=limitations,
            evidence=evidence,
            evidence_status=evidence_status,
            evidence_status_reason=evidence_status_reason,
        )

    async def _characterize_methylation(
        self, biomarker: Biomarker, *, cancer_code: str
    ) -> MolecularCharacterizationResult:
        """Methylation dimension, METADATA-ONLY integration (Phase 2 Step 0/1).

        Only GDC FILE/PROJECT-level metadata is used (file_id, data_type,
        platform, access, case count) — never a quantitative beta value or
        CpG-site ID, which the GDC REST API does not expose (see
        docs/data-feasibility-phase2.md). evidence_status becomes
        PARTIALLY_SUPPORTED when files are found — never SUPPORTED, since no
        real molecular (quantitative) characterization data is integrated.
        """
        projects = CANCER_TYPE_TO_TCGA_PROJECTS.get(cancer_code, [])
        molecular_characteristics: list[str] = []
        specificity_features: list[str] = []
        limitations: list[str] = []
        evidence: list[EvidenceRef] = [
            EvidenceRef(source=p.source, external_id=p.external_id, title=p.title)
            for p in (biomarker.papers or [])
        ]

        if not projects:
            limitations.append(
                f"{INSUFFICIENT_EVIDENCE}: no TCGA project mapping known for cancer "
                f"type '{cancer_code}'."
            )
            return MolecularCharacterizationResult(
                biomarker=biomarker.name,
                dimension="methylation",
                molecular_characteristics=molecular_characteristics,
                detectability=None,
                specificity_features=specificity_features,
                limitations=limitations,
                evidence=evidence,
                evidence_status=BiomarkerEvidenceStatus.INSUFFICIENT_EVIDENCE,
                evidence_status_reason=(
                    f"No TCGA project mapping for cancer type '{cancer_code}'."
                ),
            )

        total_files = 0
        platforms: set[str] = set()
        sample_types: set[str] = set()
        for project_id in projects:
            files = await self._gdc.search_methylation_files(project_id=project_id)
            total_files += len(files)
            for f in files:
                if f.platform:
                    platforms.add(f.platform)
                sample_types.update(f.sample_types)
                evidence.append(
                    EvidenceRef(
                        source="NCI GDC",
                        external_id=f.file_id,
                        title=f.file_name or f"{project_id} methylation array file",
                        dataset="GDC methylation array file metadata",
                        original_identifier=f.file_id,
                        access_level=f.access,
                        evidence_type="genomic_file_metadata",
                    )
                )

        if total_files > 0:
            molecular_characteristics.append(
                f"GDC methylation array file(s) identified at project level for "
                f"{', '.join(projects)}: {total_files} file(s) "
                f"(platform(s): {', '.join(sorted(platforms)) or INSUFFICIENT_EVIDENCE})."
            )
            specificity_features.append(
                "Assay platform metadata only — no CpG-site or beta-value data is "
                "integrated in this phase."
            )
            if sample_types:
                specificity_features.append(
                    f"Sample types observed in GDC file metadata: {', '.join(sorted(sample_types))}."
                )
            evidence_status = BiomarkerEvidenceStatus.PARTIALLY_SUPPORTED
            evidence_status_reason = (
                "GDC methylation array files identified at project level; no "
                "quantitative beta-value data integrated in this phase."
            )
        else:
            limitations.append(
                f"{INSUFFICIENT_EVIDENCE}: no GDC methylation array files found for "
                f"projects {', '.join(projects)}."
            )
            evidence_status = BiomarkerEvidenceStatus.INSUFFICIENT_EVIDENCE
            evidence_status_reason = (
                f"No GDC methylation array files found for projects {', '.join(projects)}."
            )

        limitations.append(
            "Methylation is METADATA-ONLY in this phase: file/project-level GDC "
            "metadata (platform, access, case linkage) only — no CpG-site or "
            "beta-value quantitative data. Real bulk methylation processing is "
            "future (Phase 3) work."
        )
        limitations.append(
            "Research use only — not a diagnostic system; findings require "
            "experimental (wet-lab) validation and carry no clinical or "
            "regulatory validity."
        )

        return MolecularCharacterizationResult(
            biomarker=biomarker.name,
            dimension="methylation",
            molecular_characteristics=molecular_characteristics,
            detectability=None,
            specificity_features=specificity_features,
            limitations=limitations,
            evidence=evidence,
            evidence_status=evidence_status,
            evidence_status_reason=evidence_status_reason,
        )

    @staticmethod
    def _evidence_status(
        *,
        molecular_characteristics: list[str],
        evidence: list[EvidenceRef],
        detectability,
    ) -> tuple[BiomarkerEvidenceStatus, str]:
        """Explicit, auditable rule for evidence strength — never derived from
        a downstream score, only from what real data was actually found.
        """
        has_characteristics = bool(molecular_characteristics)
        has_evidence = bool(evidence)
        has_detectability_data = bool(detectability and not detectability.missing_data)

        if not has_characteristics and not has_evidence:
            return (
                BiomarkerEvidenceStatus.INSUFFICIENT_EVIDENCE,
                "No molecular characteristics and no linked evidence records were found.",
            )
        if has_characteristics and has_evidence and has_detectability_data:
            return (
                BiomarkerEvidenceStatus.SUPPORTED,
                f"{len(molecular_characteristics)} molecular characteristic(s), "
                f"{len(evidence)} evidence record(s), and confirmed GDC detectability data "
                "all agree.",
            )
        return (
            BiomarkerEvidenceStatus.PARTIALLY_SUPPORTED,
            f"Some real data found ({len(molecular_characteristics)} characteristic(s), "
            f"{len(evidence)} evidence record(s)) but not all of characteristics/evidence/"
            "GDC detectability could be established.",
        )
