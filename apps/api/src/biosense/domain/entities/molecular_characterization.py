"""Domain output of the Molecular Characterization module (Phase 1, mutation dimension).

The exact field set below is a contract with the frontend/report layer — do not
rename fields. `molecular_characteristics` must be built from structured
data/literature evidence, never freely generated by an LLM; when no such
evidence exists the field is left empty and the gap is named in `limitations`.
"""

from __future__ import annotations

from dataclasses import dataclass, field

from biosense.domain.entities.biomarker_dimension import BiomarkerEvidenceStatus, EvidenceRef

INSUFFICIENT_EVIDENCE = "Insufficient evidence"


@dataclass(frozen=True)
class Detectability:
    """Whether/how the biomarker can be detected, from real records only."""

    is_detectable_in_ctdna: bool | None  # None = unknown, not "no"
    mutation_count: int | None  # from NCI GDC, if known
    basis: str  # human-readable explanation of what evidence produced this
    missing_data: bool


@dataclass(frozen=True)
class MolecularCharacterizationResult:
    """JSON shape (field names are load-bearing, see module docstring):

    {"biomarker": "", "dimension": "mutation", "molecular_characteristics": [],
     "detectability": {}, "specificity_features": [], "limitations": [],
     "evidence": []}
    """

    biomarker: str
    dimension: str  # BiomarkerDimensionType value
    molecular_characteristics: list[str] = field(default_factory=list)
    detectability: Detectability | None = None
    specificity_features: list[str] = field(default_factory=list)
    limitations: list[str] = field(default_factory=list)
    evidence: list[EvidenceRef] = field(default_factory=list)
    # Additive (Phase 1.5): explicit evidence-strength status + human-readable
    # reason. Defaulted so existing construction sites keep working; the
    # service populates these from the same real inputs it already uses.
    evidence_status: BiomarkerEvidenceStatus = BiomarkerEvidenceStatus.INSUFFICIENT_EVIDENCE
    evidence_status_reason: str = "Not yet evaluated."

    def to_dict(self) -> dict:
        return {
            "biomarker": self.biomarker,
            "dimension": self.dimension,
            "molecular_characteristics": list(self.molecular_characteristics),
            "detectability": (
                {
                    "is_detectable_in_ctdna": self.detectability.is_detectable_in_ctdna,
                    "mutation_count": self.detectability.mutation_count,
                    "basis": self.detectability.basis,
                    "missing_data": self.detectability.missing_data,
                }
                if self.detectability is not None
                else {}
            ),
            "specificity_features": list(self.specificity_features),
            "limitations": list(self.limitations),
            "evidence": [
                {
                    "source": e.source,
                    "external_id": e.external_id,
                    "title": e.title,
                    "dataset": e.dataset,
                    "original_identifier": e.original_identifier,
                    "access_date": e.access_date,
                    "access_level": e.access_level,
                    "evidence_type": e.evidence_type,
                }
                for e in self.evidence
            ],
            "evidence_status": self.evidence_status.value,
            "evidence_status_reason": self.evidence_status_reason,
        }
